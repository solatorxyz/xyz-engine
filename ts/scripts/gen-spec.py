#!/usr/bin/env python3
"""Generate lib/sdk/spec.ts from the program's own sources: layouts from program/src/state.rs (repr(C) structs, natural
alignment) and constants from perp-core/src/spec.rs. The sizes are asserted against the program (Market 896, User 2048,
Shard 10096, Slab 41056, FastBook 2192), so a layout drift fails the build instead of mis-decoding an account.
usage: python3 scripts/gen-spec.py <repo root>   (writes lib/sdk/spec.ts; the committed file is that output formatted:
       npx prettier --write lib/sdk/spec.ts)"""

import re, sys, os

root = sys.argv[1]
state = open(os.path.join(root, "program/src/state.rs")).read()
spec = open(os.path.join(root, "perp-core/src/spec.rs")).read()
state = re.sub(r"//.*", "", state)
state = re.sub(r"///.*", "", state)
consts = {}
# usize constants are plain arithmetic over earlier constants: evaluate them in source order (size_of/offset_of ones are skipped)
for m in re.finditer(r"pub const (\w+): usize = ([^;]+);", state):
    expr = m.group(2).strip()
    if "size_of" in expr or "offset_of" in expr:
        continue
    try:
        consts[m.group(1)] = int(eval(expr, {"__builtins__": {}}, dict(consts)))
    except Exception as e:
        raise SystemExit(f"cannot evaluate {m.group(1)} = {expr}: {e}")
PRIM = {"u8": (1, 1), "u16": (2, 2), "u32": (4, 4), "u64": (8, 8), "i64": (8, 8), "Key": (32, 1)}
structs = {}
for m in re.finditer(r"pub struct (\w+)\s*\{(.*?)\}", state, re.S):
    name, body = m.group(1), m.group(2)
    fields = []
    for f in re.finditer(r"pub (\w+): ([^,]+?)(?:,|$)", body.replace("\n", " ") + ","):
        fields.append((f.group(1), f.group(2).strip()))
    structs[name] = fields


def dims(t):
    inner, ds = t, []
    while inner.startswith("["):
        mm = re.match(r"\[(.+); ([^\]]+)\]$", inner)
        assert mm, t
        n = mm.group(2).strip()
        n = int(n) if n.isdigit() else (eval(n, {}, consts))
        ds.append(n)
        inner = mm.group(1).strip()
    return inner, ds


layout = {}


def size_align(t):
    inner, ds = dims(t)
    if inner in PRIM:
        s, a = PRIM[inner]
    else:
        s, a = layout_of(inner)["size"], layout_of(inner)["align"]
    for n in reversed(ds):
        s *= n
    return s, a


def layout_of(name):
    if name in layout:
        return layout[name]
    off, align, out = 0, 1, []
    for f, t in structs[name]:
        s, a = size_align(t)
        off = (off + a - 1) // a * a
        out.append((f, t, off, s))
        off += s
        align = max(align, a)
    size = (off + align - 1) // align * align
    layout[name] = {"fields": out, "size": size, "align": align}
    return layout[name]


for n in structs:
    layout_of(n)


def ts_type(t):
    inner, ds = dims(t)
    base = {"Key": "key"}.get(inner, inner if inner in PRIM else camel(inner))
    for n in reversed(ds):
        base = f"{base}[{n}]"
    return base


def camel(n):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", n).lower()


want = {"Market": 896, "User": 2048, "Shard": 10096, "Slab": 41056, "FastBook": 2192}
for k, v in want.items():
    assert layout[k]["size"] == v, (k, layout[k]["size"], v)
lines = [
    "// GENERATED by scripts/gen-spec.py from program/src/state.rs + perp-core/src/spec.rs, then formatted -- do not edit"
]
seen = set()
for m in re.finditer(
    r"pub const (\w+): (u64|usize|i64|u32|u16|u8) = (0x[0-9a-fA-F]+|-?\d+);", spec + "\n" + state
):
    k, v = m.group(1), m.group(3)
    n = int(v, 0)
    if k in seen:
        continue
    seen.add(k)
    lines.append(f"export const {k} = {n}{'n' if abs(n) >= 2**53 else ''};")
for k, v in consts.items():
    if k not in seen:
        seen.add(k)
        lines.append(f"export const {k} = {v};")
lines.append("export type Field = [string, string, number, number];")
lines.append("export const LAYOUTS: Record<string, Field[]> = {")
for n, l in layout.items():
    lines.append(
        f"  {camel(n)}: ["
        + ", ".join(f'["{f}", "{ts_type(t)}", {o}, {s}]' for f, t, o, s in l["fields"])
        + "],"
    )
lines.append("};")
lines.append(
    "export const LAYOUT_SIZE: Record<string, number> = {"
    + ", ".join(f"{camel(n)}: {l['size']}" for n, l in layout.items())
    + "};"
)
open(os.path.join(os.path.dirname(__file__), "..", "lib/sdk/spec.ts"), "w").write("\n".join(lines) + "\n")
print("spec.ts written:", len(layout), "layouts,", {k: layout[k]["size"] for k in want})
